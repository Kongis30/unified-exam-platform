const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1100,height:900}});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.route('**/api/admin/classes/*/students*', route => {
  const id = new URL(route.request().url()).pathname.split('/')[4];
  const students = id === '1' ? [{id:11,realName:'Alice',username:'alice',active:true},{id:12,realName:'Disabled',username:'disabled',active:false}] : [{id:13,realName:'Bob',username:'bob',active:true},{id:11,realName:'Alice',username:'alice',active:true}];
  return route.fulfill({json:students});
 });
 await page.route('**/api/admin/classes/available-students', route => route.fulfill({json:[{id:11,realName:'Alice',username:'alice'},{id:13,realName:'Bob',username:'bob'},{id:14,realName:'Unassigned',username:'solo'}]}));
 await page.goto(`${process.env.E2E_BASE_URL || 'http://localhost:5175'}/login`);
 await page.evaluate(async () => {
  const {createApp, reactive, h} = await import('/node_modules/.vite/deps/vue.js');
  const Dialog = (await import('/src/components/admin/ExamReleaseDialog.vue')).default;
  window.fixture = reactive({classIds:[],studentIds:[],studentTargets:[],form:{paperId:1,title:'Demo',description:'',opensAt:'2026-11-02T12:00',closesAt:'2026-11-03T12:00',durationMinutes:90,attemptLimit:1,targetScope:'SELECTED'}});
  const host=document.createElement('div'); document.body.appendChild(host);
  createApp({render(){return h(Dialog,{form:window.fixture.form,fields:{paper:'paperId',title:'title',description:'description',start:'opensAt',end:'closesAt',duration:'durationMinutes',attemptLimit:'attemptLimit',scope:'targetScope'},paperGroups:[{label:'Papers',papers:[{id:1,title:'Paper'}]}],classes:[{id:2,name:'Zulu',status:'ACTIVE',studentCount:2},{id:1,name:'Alpha',status:'ACTIVE',studentCount:1},{id:3,name:'Archived',status:'ARCHIVED'}],examType:'SAT',classIds:window.fixture.classIds,studentIds:window.fixture.studentIds,studentTargets:window.fixture.studentTargets,'onUpdate:classIds':v=>window.fixture.classIds=v,'onUpdate:studentIds':v=>window.fixture.studentIds=v,'onUpdate:studentTargets':v=>window.fixture.studentTargets=v});}}).mount(host);
 });
 const modal=page.getByRole('dialog',{name:'Create Exam'}); await modal.waitFor();
 assert.deepEqual(await modal.locator('.class-row strong').allTextContents(),['Alpha','Zulu']);
 const allClasses = modal.getByRole('checkbox', { name: 'Select all active classes' });
 await allClasses.check();
 assert.equal(await modal.getByRole('checkbox', { name: 'Select whole class Alpha' }).isChecked(), true);
 assert.equal(await modal.getByRole('checkbox', { name: 'Select whole class Zulu' }).isChecked(), true);
 await allClasses.uncheck();
 await modal.getByRole('checkbox', { name: 'Select whole class Alpha' }).check();
 assert.equal(await allClasses.evaluate(input => input.indeterminate), true);
 await modal.getByRole('button', { name: /Alpha/ }).click();
 const alpha = modal.locator('.class-item').filter({ hasText: 'Alpha' });
 await alpha.locator('.student-row').filter({hasText:'Alice'}).locator('input').check();
 assert.equal(await alpha.locator('.student-row').filter({hasText:'Disabled'}).count(),0);
 await modal.getByRole('button', { name: /Zulu/ }).click();
 const zulu = modal.locator('.class-item').filter({ hasText: 'Zulu' });
 await zulu.locator('.student-row').first().waitFor();
 assert.deepEqual(await zulu.locator('.student-row strong').allTextContents(), ['Alice', 'Bob']);
 assert.equal(await zulu.locator('.student-row').filter({hasText:'Alice'}).locator('input').isChecked(),false);
 await zulu.locator('.student-row').filter({hasText:'Alice'}).locator('input').check();
 await modal.getByRole('searchbox',{name:'Search students'}).fill('bob');
 await modal.getByText('Searching students in all classes…').waitFor({ state: 'hidden' });
 assert.deepEqual(await modal.locator('.class-row strong').allTextContents(), ['Zulu']);
 await zulu.locator('.student-row').filter({hasText:'Bob'}).locator('input').check();
 const selectionArea = modal.locator('.selected-targets');
 assert.equal(await selectionArea.getByText('View selected classes (1)').count(), 1);
 assert.equal(await selectionArea.getByText('View selected students (2)').count(), 1);
 assert.equal(await zulu.locator('.student-row').filter({hasText:'Alice'}).count(), 0);
 await modal.getByRole('button', { name: /Zulu/ }).click();
 assert.equal(await zulu.locator('.class-students').count(), 0);
 await modal.getByRole('searchbox',{name:'Search students'}).fill('');
 assert.deepEqual(await modal.locator('.class-row strong').allTextContents(), ['Alpha', 'Zulu']);
 assert.equal(await modal.getByText('Individual students', { exact: true }).count(), 0);
 const data=await page.evaluate(()=>({classIds:window.fixture.classIds,studentIds:window.fixture.studentIds,studentTargets:window.fixture.studentTargets}));
 assert.deepEqual(data,{classIds:[1],studentIds:[11,13],studentTargets:[{classId:1,studentId:11},{classId:2,studentId:11},{classId:2,studentId:13}]});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await modal.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'dialog fits mobile');
 assert.deepEqual(errors,[]);
 console.log('Shared dialog: active sorting, whole class, cross-class selection, student search, deduplication and mobile width passed');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
