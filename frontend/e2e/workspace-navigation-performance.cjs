const assert = require('node:assert/strict')
const { chromium } = require('playwright')

// 检查导航复用、目录请求去重、按 tab 加载和写入后的缓存失效。
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage()
  const requests = []
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (!url.pathname.startsWith('/api/')) return route.continue()
    requests.push(`${route.request().method()} ${url.pathname}`)
    if (url.pathname === '/api/auth/me') return route.fulfill({ json: { username: 'test', roleCode: 'ADMIN' } })
    if (url.pathname === '/api/auth/csrf') return route.fulfill({ json: { token: 'test' } })
    if (url.pathname === '/api/exam-types') return route.fulfill({ json: ['SAT', 'PSAT', 'SHSAT'].map(code => ({ code, displayName: code, workspaceCode: code, workspaceName: code })) })
    return route.fulfill({ json: [] })
  })
  const base = process.env.E2E_BASE_URL || 'http://127.0.0.1:5175'
  await page.goto(`${base}/sat`)
  await page.getByRole('tab', { name: 'Paper Management' }).waitFor()
  await page.waitForTimeout(250)
  await page.evaluate(() => { window.testHeader = document.querySelector('.admin-layout__header') })
  assert.equal(requests.filter(request => request === 'GET /api/exam-types').length, 1)
  assert.equal(requests.filter(request => request === 'GET /api/admin/classes').length, 0)
  const satPaperRequests = () => requests.filter(request => request === 'GET /api/admin/exam-types/SAT/papers').length
  assert.equal(satPaperRequests(), 1)

  await page.locator('.admin-layout__nav').getByRole('link', { name: 'PSAT', exact: true }).click()
  await page.waitForURL('**/psat')
  await page.getByRole('tab', { name: 'Paper Management' }).waitFor()
  assert.equal(await page.evaluate(() => document.querySelector('.admin-layout__header') === window.testHeader), true)
  await page.locator('.admin-layout__nav').getByRole('link', { name: 'SHSAT', exact: true }).click()
  await page.waitForURL('**/shsat')
  await page.getByRole('tab', { name: 'Paper Management' }).waitFor()
  await page.waitForTimeout(250)
  assert.equal(await page.evaluate(() => document.querySelector('.admin-layout__header') === window.testHeader), true)
  assert.equal(requests.filter(request => request === 'GET /api/admin/classes').length, 0)
  assert.equal(requests.filter(request => request === 'GET /api/exam-types').length, 1)
  await page.getByRole('tab', { name: 'Exam Release' }).click()
  await page.waitForTimeout(250)
  assert.ok(requests.some(request => request === 'GET /api/admin/classes'))

  await page.locator('.admin-layout__nav').getByRole('link', { name: 'SAT', exact: true }).click()
  await page.waitForURL('**/sat')
  await page.getByRole('tab', { name: 'Paper Management' }).waitFor()
  await page.waitForTimeout(250)
  assert.equal(satPaperRequests(), 1, 'revisiting SAT reuses the short-lived paper list')
  await page.getByRole('tab', { name: 'Classes' }).click()
  await page.waitForURL(url => url.searchParams.get('tab') === 'classes')
  await page.locator('.admin-layout__nav').getByRole('link', { name: 'PSAT', exact: true }).click()
  await page.waitForURL('**/psat')
  await page.locator('.admin-layout__nav').getByRole('link', { name: 'SAT', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/sat' && url.searchParams.get('tab') === 'classes')
  assert.equal(await page.getByRole('tab', { name: 'Classes' }).getAttribute('aria-selected'), 'true')
  await page.evaluate(async () => {
    const { apiRequest, listPapers } = await import('/src/api/platform.js')
    await apiRequest('/api/admin/test-write', { method: 'POST', body: '{}' })
    await listPapers('SAT')
  })
  assert.equal(satPaperRequests(), 2, 'successful writes invalidate cached paper lists')
  assert.deepEqual(errors, [])
  await page.close()
  for (const role of ['TEACHER', 'STUDENT']) {
    const rolePage = await browser.newPage()
    const roleErrors = []
    rolePage.on('pageerror', error => roleErrors.push(error.message))
    await rolePage.route('**/*', route => {
      const url = new URL(route.request().url())
      if (!url.pathname.startsWith('/api/')) return route.continue()
      if (url.pathname === '/api/auth/me') return route.fulfill({ json: { username: role.toLowerCase(), roleCode: role } })
      if (url.pathname === '/api/exam-types') return route.fulfill({ json: ['SAT', 'PSAT', 'SHSAT'].map(code => ({ code, displayName: code, workspaceCode: code, workspaceName: code })) })
      return route.fulfill({ json: [] })
    })
    await rolePage.goto(`${base}/sat`)
    if (role === 'TEACHER') await rolePage.getByRole('tab', { name: 'Classes' }).waitFor()
    else await rolePage.getByRole('heading', { name: 'Your exams' }).waitFor()
    const nav = role === 'TEACHER' ? '.admin-layout__nav' : '.main-layout__nav'
    await rolePage.locator(nav).getByRole('link', { name: 'SHSAT', exact: true }).click()
    await rolePage.waitForURL('**/shsat')
    if (role === 'TEACHER') await rolePage.getByRole('tab', { name: 'Classes' }).waitFor()
    else await rolePage.getByRole('heading', { name: 'Your exams' }).waitFor()
    assert.deepEqual(roleErrors, [], `${role} navigation has no page errors`)
    await rolePage.close()
  }
  const studentPage = await browser.newPage()
  let releasePractice
  const practiceGate = new Promise(resolve => { releasePractice = resolve })
  await studentPage.route('**/*', async route => {
    const url = new URL(route.request().url())
    if (!url.pathname.startsWith('/api/')) return route.continue()
    if (url.pathname === '/api/auth/me') return route.fulfill({ json: { username: 'student', roleCode: 'STUDENT' } })
    if (url.pathname === '/api/exam-types') return route.fulfill({ json: [{ code: 'SAT', displayName: 'SAT', workspaceCode: 'SAT' }] })
    if (url.pathname === '/api/student/exams') return route.fulfill({ json: [{ id: 1, title: 'Assigned exam', paperTitle: 'Paper', examTypeCode: 'SAT', status: 'PUBLISHED', opensAt: '2020-01-01T00:00:00Z', closesAt: '2099-01-01T00:00:00Z' }] })
    if (url.pathname === '/api/student/sat-practice-papers') await practiceGate
    return route.fulfill({ json: [] })
  })
  await studentPage.goto(`${base}/sat`)
  await studentPage.getByText('Assigned exam', { exact: true }).waitFor({ timeout: 5000 })
  assert.equal(await studentPage.getByText('Loading practice papers...').count(), 1)
  releasePractice()
  await studentPage.getByText('Loading practice papers...').waitFor({ state: 'hidden' })
  await studentPage.close()
  await browser.close()
  console.log('Persistent navigation, request deduplication, lazy tab loading and cache invalidation passed')
})().catch(error => { console.error(error); process.exit(1) })
